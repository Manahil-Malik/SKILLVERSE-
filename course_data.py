import re


def _whole_phrase_match(haystack: str, phrase: str) -> bool:
    
    pattern = r"(?<![a-z0-9])" + re.escape(phrase) + r"(?![a-z0-9])"
    return re.search(pattern, haystack) is not None


def get_courses_for_skill(skill_name: str):
    """
    Looks up courses for a skill string from Gemini.
    Tries direct match -> alias -> whole-phrase match in either.
    Returns [] if nothing found (no random fallback links).
    """
    key = skill_name.strip().lower()

    if key in COURSE_MAP:
        return COURSE_MAP[key]

    if key in SKILL_ALIASES:
        return COURSE_MAP.get(SKILL_ALIASES[key], [])

    # check longest keys first so "html css" wins over shorter overlaps
    for known_skill in sorted(COURSE_MAP, key=len, reverse=True):
        if _whole_phrase_match(key, known_skill):
            return COURSE_MAP[known_skill]
    for alias, canonical in sorted(SKILL_ALIASES.items(), key=lambda kv: len(kv[0]), reverse=True):
        if _whole_phrase_match(key, alias):
            return COURSE_MAP.get(canonical, [])

    return []
